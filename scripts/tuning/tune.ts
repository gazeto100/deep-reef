import { writeFileSync } from 'node:fs';
import { analyzeRound } from '../../src/math/analysis/exact';
import { reelFingerprint } from '../../src/math/analysis/fingerprint';
import { simulate } from '../../src/math/analysis/simulator';
import { DEEP_REEF } from '../../src/math/config/deepReef';
import { compileGame } from '../../src/math/engine/compile';
import type { GameDefinition, PayByCount } from '../../src/math/engine/types';
import { DEEP_REEF_RULES, type DeepReefSymbol } from '../../src/math/config/deepReefRules';
import { CANDIDATES, type Candidate } from './candidates';
import { layoutStrip } from './layoutStrip';

/**
 * Usage:
 *   npm run math:tune               -> summary row for every candidate
 *   npm run math:tune -- v3         -> summary for one candidate
 *   npm run math:tune -- v3 --detail -> RTP by symbol for base and free-spin reels
 *   npm run math:tune -- v3 --emit  -> also print the reel strips as JSON
 *   npm run math:tune -- v3 --write -> freeze the candidate into src/math/config/deepReef.ts
 *                                      (refuses to change the base reels unless --allow-base-change)
 *   --rounds N                      -> rounds of the quick SD/tail simulation (default 2M, seed 1)
 */

export function buildDefinition(candidate: Candidate): GameDefinition<DeepReefSymbol> {
  // The stack rule is enabled per reel set, and only when that set declares stacks (even
  // empty ones, as v10-v12 did for base). A set without stacks is laid out under the
  // original no-neighbours rule and so reproduces the pre-stack strips exactly. Enabling
  // the rule changes which shuffle attempt is accepted first, even with the same seed.
  const layout = (
    counts: Candidate['baseReels'],
    stacks: Candidate['baseStacks'],
    seedOffset: number,
  ): DeepReefSymbol[][] =>
    counts.map((c, reel) => {
      const usesStacks = stacks !== undefined;
      const reelStacks = stacks?.[reel];
      return layoutStrip<DeepReefSymbol>(c, {
        scatter: DEEP_REEF_RULES.scatter,
        rowCount: DEEP_REEF_RULES.rowCount,
        stackable: usesStacks ? DEEP_REEF_RULES.constraints.stackable : [],
        maxStack: usesStacks ? DEEP_REEF_RULES.constraints.maxStack : 1,
        seed: candidate.layoutSeed * 1000 + seedOffset + reel,
        ...(reelStacks ? { stacks: reelStacks } : {}),
      });
    });

  return {
    ...DEEP_REEF_RULES,
    linePays: candidate.linePays,
    scatterPays: candidate.scatterPays,
    baseReels: layout(candidate.baseReels, candidate.baseStacks, 0),
    freeSpinReels: layout(candidate.freeSpinReels, candidate.freeSpinStacks, 100),
  };
}

const pct = (x: number, digits = 2): string => `${(x * 100).toFixed(digits)}%`;

const CONFIG_PATH = 'src/math/config/deepReef.ts';

/**
 * Freezes a candidate into the game config as literal data. The strips are written
 * out, not regenerated at runtime, so they cannot silently change if the layout code
 * or the RNG ever does.
 */
function renderConfig(candidate: Candidate, def: GameDefinition<DeepReefSymbol>): string {
  const pays = (p: PayByCount): string =>
    `{ ${Object.entries(p)
      .map(([k, v]) => `${k}: ${v}`)
      .join(', ')} }`;
  const strip = (s: readonly string[]): string => {
    const rows: string[] = [];
    for (let i = 0; i < s.length; i += 8) {
      rows.push(`      ${s.slice(i, i + 8).map((x) => `'${x}'`).join(', ')},`);
    }
    return `    [\n${rows.join('\n')}\n    ],`;
  };
  const reelSet = (reels: readonly (readonly string[])[]): string => reels.map(strip).join('\n');
  const linePays = Object.entries(def.linePays)
    .map(([symbol, p]) => `    ${symbol}: ${pays(p ?? {})},`)
    .join('\n');

  return `// Generated by \`npm run math:tune -- ${candidate.id} --write\` (see docs/math-tuning.md).
// Frozen literal data: edit the candidate and regenerate rather than editing by hand.
import type { GameDefinition } from '../engine/types';
import { DEEP_REEF_RULES, type DeepReefSymbol } from './deepReefRules';

export const DEEP_REEF: GameDefinition<DeepReefSymbol> = {
  ...DEEP_REEF_RULES,
  // Multiples of line bet (total bet / 20).
  linePays: {
${linePays}
  },
  // Multiples of total bet, anywhere on the screen.
  scatterPays: ${pays(def.scatterPays)},
  baseReels: [
${reelSet(def.baseReels)}
  ],
  freeSpinReels: [
${reelSet(def.freeSpinReels)}
  ],
};
`;
}

function main(): void {
  const args = process.argv.slice(2);
  const emit = args.includes('--emit');
  const roundsFlag = args.indexOf('--rounds');
  const quickRounds = roundsFlag >= 0 ? Number(args[roundsFlag + 1]) : 2_000_000;
  const ids = args.filter((a, i) => !a.startsWith('--') && (roundsFlag < 0 || i !== roundsFlag + 1));
  const selected = ids.length > 0 ? CANDIDATES.filter((c) => ids.includes(c.id)) : CANDIDATES;
  if (selected.length === 0) throw new Error(`unknown candidate(s): ${ids.join(', ')}`);

  const rows = selected.map((candidate) => {
    const started = performance.now();
    const def = buildDefinition(candidate);
    const a = analyzeRound(compileGame(def));
    // SD and the tail cannot be computed exactly (feature variance with retriggers),
    // so a quick simulation estimates them during tuning.
    const sim = simulate(def, { rounds: quickRounds, seed: 1, totalBet: DEEP_REEF_RULES.betLevels[0] ?? 20 });
    const seconds = ((performance.now() - started) / 1000).toFixed(1);

    if (args.includes('--detail')) {
      for (const [name, set] of [
        ['base', a.base],
        ['free spins (x1)', a.freeSpins],
      ] as const) {
        console.log(`\n${candidate.id} ${name}: line RTP by symbol and count`);
        const bySymbol = new Map<string, Record<string, string>>();
        for (const s of set.lineStats) {
          const row = bySymbol.get(s.symbol) ?? {};
          row[`x${s.count}`] = pct(s.rtp);
          bySymbol.set(s.symbol, row);
        }
        console.table(Object.fromEntries(bySymbol));
        console.log(`with wild: ${pct(set.rtpLinesWithWild)} of ${pct(set.rtpLines)}`);
      }
    }

    if (args.includes('--write')) {
      const current = reelFingerprint(DEEP_REEF.baseReels);
      const next = reelFingerprint(def.baseReels);
      if (current !== next && !args.includes('--allow-base-change')) {
        throw new Error(
          `${candidate.id} would change the base reels (${current} -> ${next}). ` +
            'Pass --allow-base-change if that is intended, and update the pinned fingerprint in deepReef.test.ts.',
        );
      }
      writeFileSync(CONFIG_PATH, renderConfig(candidate, def));
      console.log(`wrote ${CONFIG_PATH} from ${candidate.id}`);
    }

    if (emit) {
      console.log(`// ${candidate.id}: ${candidate.note}`);
      console.log(`baseReels: ${JSON.stringify(def.baseReels)},`);
      console.log(`freeSpinReels: ${JSON.stringify(def.freeSpinReels)},`);
    }

    return {
      id: candidate.id,
      'base lines': pct(a.base.rtpLines),
      'base scatter': pct(a.base.rtpScatter),
      'FS (uncapped)': pct(a.rtpFeatureUncapped),
      'RTP (uncapped)': pct(a.rtpUncapped, 3),
      'hit rate': pct(a.hitRate),
      'FS 1 in': (1 / a.triggerProbability).toFixed(0),
      'FS spins avg': a.expectedFreeSpinsPerFeature.toFixed(2),
      'FS avg win (x bet)': a.featureMeanUncapped.toFixed(1),
      'base SD (x bet)': Math.sqrt(a.base.winVariance).toFixed(2),
      'FS spin SD x1 (exact)': Math.sqrt(a.freeSpins.winVariance).toFixed(2),
      'SD (sim)': sim.roundWin.sd.toFixed(2),
      'max (sim)': `${sim.maxRound.win.toFixed(0)}x`,
      '>=1000x (sim)': sim.roundsAtLeast.find((t) => t.threshold === 1000)?.count ?? 0,
      's': seconds,
    };
  });

  console.table(rows);
}

main();
